// ==================== SCROLLSPY & STICKY NAV SYNC ====================
function initScrollSpy() {
  const sections = document.querySelectorAll(".menu-category");
  const navContainer = document.getElementById("category-nav-container");
  const navLinks = document.querySelectorAll(".category-pill-link");

  if (!sections.length || !navLinks.length) return;

  function onScroll() {
    const scrollPos = window.scrollY + 160;
    let currentId = "";

    sections.forEach((section) => {
      const top = section.offsetTop;
      const height = section.offsetHeight;
      if (scrollPos >= top && scrollPos < top + height) {
        currentId = section.id;
      }
    });

    if (!currentId && sections.length > 0 && window.scrollY < sections[0].offsetTop) {
      currentId = sections[0].id;
    }

    if (currentId) {
      navLinks.forEach((link) => {
        const href = link.getAttribute("href");
        if (href === `#${currentId}`) {
          if (!link.classList.contains("active")) {
            navLinks.forEach((l) => l.classList.remove("active"));
            link.classList.add("active");

            // Auto-scroll the pill into view inside the horizontal nav bar
            if (navContainer) {
              const linkLeft = link.offsetLeft;
              const linkWidth = link.offsetWidth;
              const containerWidth = navContainer.clientWidth;
              const scrollTarget = linkLeft - containerWidth / 2 + linkWidth / 2;
              navContainer.scrollTo({
                left: Math.max(0, scrollTarget),
                behavior: "smooth",
              });
            }
          }
        }
      });
    }
  }

  // Click handler to immediately set active pill
  navLinks.forEach((link) => {
    link.addEventListener("click", function () {
      navLinks.forEach((l) => l.classList.remove("active"));
      this.classList.add("active");
    });
  });

  // RequestAnimationFrame throttled scroll
  let isThrottled = false;
  window.addEventListener(
    "scroll",
    () => {
      if (!isThrottled) {
        window.requestAnimationFrame(() => {
          onScroll();
          isThrottled = false;
        });
        isThrottled = true;
      }
    },
    { passive: true },
  );

  onScroll();
}

// Initial boot
syncMenuFromStorage();
updatecart();
