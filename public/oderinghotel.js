const menuCatalog = document.querySelector(".menu-catalog");

menuCatalog.addEventListener("click", function (event) {
  const button = event.target.closest("button");
  const cardBottom = button?.closest(".food-card-bottom");
  if (!button || !cardBottom) return;

  const product = Menu.find((item) => item.id === cardBottom.dataset.id);
  if (!product) return;

  if (button.classList.contains("add_Items")) {
    product.quantity = Math.max(product.quantity, 1);
    renderQuantityControl(cardBottom, product.quantity);
  } else if (button.classList.contains("plus")) {
    product.quantity++;
    cardBottom.querySelector(".qty-value").textContent = product.quantity;
  } else if (button.classList.contains("minus")) {
    product.quantity = Math.max(product.quantity - 1, 0);
    if (product.quantity === 0) {
      renderAddButton(cardBottom);
    } else {
      cardBottom.querySelector(".qty-value").textContent = product.quantity;
    }
  } else {
    return;
  }

  updatecart();
});

function renderQuantityControl(cardBottom, quantity) {
  cardBottom.innerHTML = `<div class="quantity-control">
    <button class="qty-btn minus" type="button" aria-label="Decrease quantity">−</button>
    <span class="qty-value">${quantity}</span>
    <button class="qty-btn plus" type="button" aria-label="Increase quantity">+</button>
  </div>`;
}

function renderAddButton(cardBottom) {
  cardBottom.innerHTML = '<button type="button" class="add_Items">Add</button>';
}
function updateFabBadge() {
  let itemCount = Menu.reduce((total, item) => total + item.quantity, 0);
  let badge = document.querySelector("#cart-fab-count");

  badge.textContent = itemCount;
  badge.style.display = itemCount > 0 ? "flex" : "none";
}

function updatecart() {
  let cartItems = Menu.filter((item) => item.quantity > 0);
  let drawer = document.querySelector("#cart-footer");
  let cartContainer = document.querySelector("#cart-items");
  let cartStatus = document.querySelector("#cart-status");
  let cartBody = document.querySelector("#cart-details");
  let totalSection = document.querySelector("#cart-total");
  let cartSummary = document.querySelector("#cart-summary");

  if (!cartBody) {
    cartBody = document.createElement("div");
    cartBody.id = "cart-details";
    cartBody.className = "cart-drawer-body";
    drawer.insertBefore(cartBody, cartContainer);
    cartBody.appendChild(cartContainer);
  }

  if (cartItems.length === 0) {
    localStorage.setItem("cartItems", JSON.stringify([]));
    cartContainer.replaceChildren();
    cartContainer.insertAdjacentHTML(
      "beforeend",
      '<li class="empty-cart-state" id="empty-cart">Your cart is empty.</li>',
    );
    if (totalSection) {
      totalSection.remove();
    }
    if (cartSummary) {
      cartSummary.remove();
    }
    cartStatus.textContent = "Your cart is empty.";
    updateFabBadge();
    return;
  }

  const itemMarkup = cartItems
    .map(
      (item) => `<li class="cart-item-row">
        <p class="cart-item-name">${item.name} x ${item.quantity}</p>
        <span class="cart-item-total">₹${item.quantity * item.price}</span>
      </li>`,
    )
    .join("");
  let grandTotal = cartItems.reduce(
    (total, item) => total + item.quantity * item.price,
    0,
  );

  cartContainer.replaceChildren();
  cartContainer.insertAdjacentHTML("beforeend", itemMarkup);

  if (!totalSection) {
    totalSection = document.createElement("div");
    totalSection.id = "cart-total";
    totalSection.className = "cart-total-section";
    cartContainer.insertAdjacentElement("afterend", totalSection);
  }

  totalSection.innerHTML = `<span class="cart-total-label">Grand Total</span>
    <span class="grand-total-amount" id="grand-cart-total">₹${grandTotal}</span>`;

  if (!cartSummary) {
    cartSummary = document.createElement("div");
    cartSummary.id = "cart-summary";
    cartSummary.className = "cart-drawer-footer";
    drawer.appendChild(cartSummary);
  }

  cartSummary.innerHTML = `
    <button
      class="cart-action-btn btn-clear"
      id="clear-cart-btn"
      type="button">
      🗑 Clear
    </button>
    <button
      class="cart-action-btn btn-checkout"
      id="checkout-btn"
      type="button">
      Checkout →
    </button>
  `;

  cartStatus.textContent = "Your Cart:";
  updateFabBadge();

  // Save current cart items to localStorage so cart.html is always in sync
  localStorage.setItem("cartItems", JSON.stringify(cartItems));

  const clearBtn = document.getElementById("clear-cart-btn");
  if (clearBtn) {
    clearBtn.onclick = function (e) {
      e.preventDefault();
      clearCartItems();
    };
  }

  const checkoutBtn = document.getElementById("checkout-btn");
  if (checkoutBtn) {
    checkoutBtn.onclick = function (e) {
      e.preventDefault();
      checkout();
    };
  }
}

function syncMenuFromStorage() {
  try {
    const saved = localStorage.getItem("cartItems");
    if (saved) {
      const items = JSON.parse(saved);
      if (Array.isArray(items)) {
        items.forEach((savedItem) => {
          const menuItem = Menu.find((m) => m.id === savedItem.id);
          if (menuItem) {
            menuItem.quantity = savedItem.quantity;
          }
        });
      }
    }
  } catch (e) {
    console.error("Failed to load cartItems from storage:", e);
  }

  // Update card UI values
  Menu.forEach((item) => {
    const cardBottom = document.querySelector(
      `.food-card-bottom[data-id="${item.id}"]`,
    );
    if (cardBottom) {
      if (item.quantity > 0) {
        renderQuantityControl(cardBottom, item.quantity);
      }
    }
  });
}

